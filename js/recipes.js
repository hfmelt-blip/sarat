export const builtinKcal = (r) => r.ing.reduce((a, i) => a + i.kcal, 0);
export const builtinById = (id) => BUILTIN.find((r) => r.id === id);

export const totals = (s) => ({
  kcal: s.ingredients.reduce((a, i) => a + i.calories, 0),
  p: s.ingredients.reduce((a, i) => a + i.proteinG, 0),
  c: s.ingredients.reduce((a, i) => a + i.carbsG, 0),
  f: s.ingredients.reduce((a, i) => a + i.fatG, 0),
});

export function judge(s, goals) {
  const t = totals(s);
  const kcal = Math.max(1, t.kcal);
  const cs = t.c * 4 / kcal, fs = t.f * 9 / kcal, ps = t.p * 4 / kcal;
  if (cs > carbShare(goals) + 0.15) return ['OK_WITH_CHANGES', 'الكارب فيها أعلى من المناسب لهدفك. قلّل التمن أو الخبز للنص وزيد الخضار.'];
  if (goals.includes('OBESITY_LIPIDS') && fs > 0.40) return ['OK_WITH_CHANGES', 'الدهون فيها عالية لهدفك. قلّل الزيت للنص.'];
  if (ps >= 0.25) return ['GOOD', 'وجبة متوازنة وبروتينها عالي، تشبّع وتناسب هدفك.'];
  return ['GOOD', 'وجبة متوازنة تناسب هدفك.'];
}

const trim = (d) => String(Math.round(d * 100) / 100);

export function scaleIng(i, f) {
  return { ...i, grams: Math.round(i.grams * f), calories: Math.round(i.calories * f), proteinG: i.proteinG * f, carbsG: i.carbsG * f, fatG: i.fatG * f };
}

/** الوصفة الجاهزة كاقتراح بنفس شكل اقتراح Gemini. */
export function builtinToSuggestion(r, goals, pantry = null, factor = 1) {
  const pk = pantry ? dishKey(pantry) : null;
  const ingredients = r.ing.map((i) => ({
    name: i.name,
    amount: factor === 1 ? i.amount : `${i.amount} × ${trim(factor)}`,
    grams: Math.round(i.grams * factor), calories: Math.round(i.kcal * factor),
    proteinG: i.p * factor, carbsG: i.c * factor, fatG: i.f * factor,
    available: pk == null || !i.key || pk.includes(dishKey(i.key)),
  }));
  const base = { possible: true, dishName: r.name, ingredients, steps: r.steps, prepMinutes: r.prep, verdict: 'GOOD', summary: '', note: '' };
  const [verdict, summary] = judge(base, goals);
  const note = [r.note || '', factor !== 1 ? `الكمية معدّلة لتناسب سعرات وجبتك (× ${trim(factor)}).` : ''].filter(Boolean).join(' ');
  return { ...base, verdict, summary, note };
}

