/**
 * مكوّن بوصفة محفوظة. [key] = كلمة نبحث عنها بالمكونات المتوفرة بالبيت،
 * وفارغة للأساسيات اللي بكل بيت (زيت، ملح، بهارات، ليمون).
 */
data class BIng(
    val name: String,
    val amount: String,
    val grams: Int,
    val kcal: Int,
    val p: Double,
    val c: Double,
    val f: Double,
    val key: String,
)

data class BuiltinRecipe(
    val id: String,
    val name: String,
    val slots: Set<MealSlot>,
    val prepMinutes: Int,
    val ingredients: List<BIng>,
    val steps: List<String>,
    val note: String = "",
) {
    val kcal: Int get() = ingredients.sumOf { it.kcal }

    /** الوصفة كاقتراح، مع تقييم حسب أهداف المستخدم وعلامة على الناقص من البيت. */
    fun toSuggestion(goals: Set<DietGoal>, pantry: String? = null, factor: Double = 1.0): MealSuggestion {
        val pantryKey = pantry?.let { dishKey(it) }
        val items = ingredients.map { i ->
            val available = pantryKey == null || i.key.isEmpty() || pantryKey.contains(dishKey(i.key))
            PlanIngredient(
                name = i.name,
                amount = if (factor == 1.0) i.amount else "${i.amount} × ${trim(factor)}",
                grams = (i.grams * factor).toInt(),
                calories = (i.kcal * factor).toInt(),
                proteinG = i.p * factor,
                carbsG = i.c * factor,
                fatG = i.f * factor,
                available = available,
            )
        }
        val base = MealSuggestion(
            possible = true,
            dishName = name,
            ingredients = items,
            steps = steps,
            prepMinutes = prepMinutes,
        )
        val (verdict, summary) = LocalJudge.judge(base, goals)
        val notes = listOf(
            note,
            if (factor != 1.0) "الكمية معدّلة لتناسب سعرات وجبتك (× ${trim(factor)})." else "",
        ).filter { it.isNotBlank() }.joinToString(" ")
        return base.copy(verdict = verdict, summary = summary, note = notes)
    }

    private fun trim(d: Double): String {
        val s = String.format(java.util.Locale.US, "%.2f", d).trimEnd('0').trimEnd('.')
        return s
    }
}

/** تقييم بسيط للوصفات المحفوظة حسب الهدف، بدون Gemini. */
object LocalJudge {
    fun judge(s: MealSuggestion, goals: Set<DietGoal>): Pair<String, String> {
        val kcal = s.totalCalories.coerceAtLeast(1)
        val carbShare = s.totalCarbs * 4 / kcal
        val fatShare = s.totalFat * 9 / kcal
        val proteinShare = s.totalProtein * 4 / kcal
        val carbLimit = goals.minOfOrNull { it.carbShare } ?: 0.45
        return when {
            carbShare > carbLimit + 0.15 ->
                "OK_WITH_CHANGES" to "الكارب فيها أعلى من المناسب لهدفك. قلّل التمن أو الخبز للنص وزيد الخضار."
            DietGoal.OBESITY_LIPIDS in goals && fatShare > 0.40 ->
                "OK_WITH_CHANGES" to "الدهون فيها عالية لهدفك. قلّل الزيت للنص."
            proteinShare >= 0.25 ->
                "GOOD" to "وجبة متوازنة وبروتينها عالي، تشبّع وتناسب هدفك."
            else ->
                "GOOD" to "وجبة متوازنة تناسب هدفك."
        }
    }
}

